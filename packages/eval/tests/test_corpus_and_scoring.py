def test_document_cer_scores_the_markdown_not_raw_text(fixture_by_id, result_for):
    digital = fixture_by_id["digital-pdf"]
    polished_markdown = result_for(digital, raw_text="völlig falscher Rohtext")
    assert score_fixture(digital, polished_markdown)["cer"] == 0
    perfect_raw = result_for(digital, markdown="völlig falsches Markdown", raw_text=digital.reference)
    assert score_fixture(digital, perfect_raw)["cer"] > 0.5


def test_normalization_keeps_umlauts_and_drops_markup():
    assert normalize("Die Straße, über die Brücke!") == "die straße über die brücke"
    assert score("Größere Schäden.", "größere schäden") == {"wer": 0.0, "cer": 0.0, "ref_words": 2, "hyp_words": 2}


def test_perfect_results_score_zero(perfect_runs):
    for run in perfect_runs:
        metrics = score_fixture(run.fixture, run.result)
        attribution = metrics.pop("speaker_attribution", 1.0)
        assert attribution == 1.0 and all(value == 0 for value in metrics.values()), (run.fixture.id, metrics)


def test_diarization_scores_speaker_metrics(fixture_by_id, result_for):
    fixture = fixture_by_id["de-case-conference"]
    perfect = score_fixture(fixture, result_for(fixture))
    assert {k: perfect[k] for k in ("speaker_attribution", "der", "speaker_count_error")} == {
        "speaker_attribution": 1.0, "der": 0.0, "speaker_count_error": 0}
    merged = [s.model_copy(update={"speaker": 1}) for s in result_for(fixture).segments]
    one_voice = score_fixture(fixture, result_for(fixture, segments=merged))
    assert 0 < one_voice["speaker_attribution"] < 0.6 and one_voice["der"] > 0.4
    assert one_voice["speaker_count_error"] == 3


def test_diarization_result_without_speakers_attributes_nothing(fixture_by_id, result_for):
    fixture = fixture_by_id["de-two-speakers"]
    unattributed = [s.model_copy(update={"speaker": None}) for s in result_for(fixture).segments]
    for segments in (unattributed, []):
        metrics = score_fixture(fixture, result_for(fixture, segments=segments))
        assert (metrics["speaker_attribution"], metrics["der"]) == (0.0, 1.0)
        assert metrics["wer"] == 0.0


def test_removed_table_cell_and_swapped_columns_are_detected(fixture_by_id, result_for):
    table = fixture_by_id["table-columns-pdf"]
    markdown = result_for(table).markdown
    without_cell = markdown.replace("| Fuß 9 |", "|  |")
    assert missing_table_cells(without_cell, table.table_cells) == ["Fuß 9"]
    left, right = table.reading_order[4], table.reading_order[6]
    swapped = markdown.replace(left, "@@").replace(right, left).replace("@@", right)
    assert reading_order_failures(swapped, table.reading_order) > 0
    metrics = score_fixture(table, result_for(table, markdown=without_cell))
    assert metrics["missing_cells"] == 1


def test_cells_outside_a_table_count_as_missing(fixture_by_id, result_for):
    table = fixture_by_id["table-columns-pdf"]
    flattened = table.reference  # every cell as plain text, no table structure
    assert score_fixture(table, result_for(table, markdown=flattened))["missing_cells"] == len(table.table_cells)


def test_words_on_silence_are_counted(fixture_by_id, result_for):
    silence = fixture_by_id["silence"]
    assert score_fixture(silence, result_for(silence, text=""))["silence_insertions"] == 0
    hallucinated = result_for(silence, text="Untertitel im Auftrag des ZDF.")
    assert score_fixture(silence, hallucinated)["silence_insertions"] == 5

"""The committed corpus is synthetic and pinned; scoring turns results into numbers only."""
import hashlib
import json
import shutil

import pytest
from resona_eval import CorpusError, load_corpus, score_fixture
from resona_eval.metrics import missing_table_cells, normalize, reading_order_failures, score


def test_committed_corpus_is_pinned_synthetic_and_licensed(corpus):
    manifest = (corpus.root / "MANIFEST.json").read_bytes()
    assert corpus.sha256 == hashlib.sha256(manifest).hexdigest()
    kinds = {f.kind for f in corpus.fixtures}
    assert kinds == {"audio", "document"}
    for fixture in corpus.fixtures:
        assert fixture.license.startswith("CC0-1.0, generated by eval/corpus/make_corpus.py")
        assert "synthetic" in fixture.source
        assert (corpus.root / fixture.file).stat().st_size < 1_000_000
    assert (corpus.root / "make_corpus.py").is_file()
    checks = {c for f in corpus.fixtures for c in f.checks}
    assert checks == {"wer", "cer", "silence", "table_cells", "reading_order"}


def test_tampered_fixture_is_refused(corpus, tmp_path):
    copy = tmp_path / "corpus"
    shutil.copytree(corpus.root, copy)
    target = copy / corpus.fixtures[0].file
    target.write_bytes(target.read_bytes() + b"\0")
    with pytest.raises(CorpusError, match="does not match"):
        load_corpus(copy)


def test_fixture_path_must_stay_inside_corpus(corpus, tmp_path):
    copy = tmp_path / "corpus"
    shutil.copytree(corpus.root, copy)
    manifest = json.loads((copy / "MANIFEST.json").read_text(encoding="utf-8"))
    manifest["fixtures"][0]["file"] = "../outside.wav"
    (copy / "MANIFEST.json").write_text(json.dumps(manifest), encoding="utf-8")
    with pytest.raises(CorpusError, match="plain name"):
        load_corpus(copy)


def test_normalization_keeps_umlauts_and_drops_markup():
    assert normalize("Die Straße, über die Brücke!") == "die straße über die brücke"
    assert score("Größere Schäden.", "größere schäden") == {"wer": 0.0, "cer": 0.0, "ref_words": 2, "hyp_words": 2}


def test_perfect_results_score_zero(perfect_runs):
    for run in perfect_runs:
        metrics = score_fixture(run.fixture, run.result)
        assert all(value == 0 for value in metrics.values()), (run.fixture.id, metrics)


def test_removed_table_cell_and_swapped_columns_are_detected(fixture_by_id, result_for):
    table = fixture_by_id["table-columns-pdf"]
    markdown = result_for(table).markdown
    without_cell = markdown.replace("| Fuß 9 |", "|  |")
    assert missing_table_cells(without_cell, table.table_cells) == ["Fuß 9"]
    left, right = table.reading_order[4], table.reading_order[6]
    swapped = markdown.replace(left, "@@").replace(right, left).replace("@@", right)
    assert reading_order_failures(swapped, table.reading_order) > 0
    metrics = score_fixture(table, result_for(table, markdown=without_cell))
    assert metrics["missing_cells"] == 1


def test_cells_outside_a_table_count_as_missing(fixture_by_id, result_for):
    table = fixture_by_id["table-columns-pdf"]
    flattened = table.reference  # every cell as plain text, no table structure
    assert score_fixture(table, result_for(table, markdown=flattened))["missing_cells"] == len(table.table_cells)


def test_words_on_silence_are_counted(fixture_by_id, result_for):
    silence = fixture_by_id["silence"]
    assert score_fixture(silence, result_for(silence, text=""))["silence_insertions"] == 0
    hallucinated = result_for(silence, text="Untertitel im Auftrag des ZDF.")
    assert score_fixture(silence, hallucinated)["silence_insertions"] == 5

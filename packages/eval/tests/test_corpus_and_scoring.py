"""The committed corpus is synthetic and pinned; scoring turns results into numbers only."""
import hashlib
import json
import shutil

import pytest
from resona_eval import CorpusError, load_corpus, score_fixture
from resona_eval.metrics import missing_table_cells, normalize, reading_order_failures, score


def test_committed_corpus_is_pinned_synthetic_and_licensed(corpus):
    manifest = (corpus.root / "MANIFEST.json").read_bytes()
    assert corpus.sha256 == hashlib.sha256(manifest).hexdigest()
    kinds = {f.kind for f in corpus.fixtures}
    assert kinds == {"audio", "document"}
    for fixture in corpus.fixtures:
        assert fixture.license.startswith("CC0-1.0, generated by eval/corpus/make_corpus.py")
        assert "synthetic" in fixture.source
        assert (corpus.root / fixture.file).stat().st_size < (3_000_000 if fixture.speakers else 1_000_000)
    assert (corpus.root / "make_corpus.py").is_file()
    checks = {c for f in corpus.fixtures for c in f.checks}
    assert checks == {"wer", "cer", "silence", "table_cells", "reading_order", "speaker_attribution", "der",
                      "speaker_count"}


def test_tampered_fixture_is_refused(corpus, tmp_path):
    copy = tmp_path / "corpus"
    shutil.copytree(corpus.root, copy)
    target = copy / corpus.fixtures[0].file
    target.write_bytes(target.read_bytes() + b"\0")
    with pytest.raises(CorpusError, match="does not match"):
        load_corpus(copy)


def test_fixture_path_must_stay_inside_corpus(corpus, tmp_path):
    copy = tmp_path / "corpus"
    shutil.copytree(corpus.root, copy)
    manifest = json.loads((copy / "MANIFEST.json").read_text(encoding="utf-8"))
    manifest["fixtures"][0]["file"] = "../outside.wav"
    (copy / "MANIFEST.json").write_text(json.dumps(manifest), encoding="utf-8")
    with pytest.raises(CorpusError, match="plain name"):
        load_corpus(copy)


def _with_manifest_change(corpus, tmp_path, fixture_id, **changes):
    copy = tmp_path / "corpus"
    shutil.copytree(corpus.root, copy)
    manifest = json.loads((copy / "MANIFEST.json").read_text(encoding="utf-8"))
    entry = next(f for f in manifest["fixtures"] if f["id"] == fixture_id)
    entry.update(changes)
    (copy / "MANIFEST.json").write_text(json.dumps(manifest), encoding="utf-8")
    return copy


@pytest.mark.parametrize("options", [{"ocr": "sometimes"}, {"images_scale_typo": 2}, {"page_start": 0},
                                     {"languages": ["nl"]}])
def test_invalid_document_fixture_option_is_refused(corpus, tmp_path, options):
    copy = _with_manifest_change(corpus, tmp_path, "scan-pdf", options=options)
    with pytest.raises(CorpusError, match="invalid document options"):
        load_corpus(copy)


@pytest.mark.parametrize("options", [{"vad_filter": "sometimes"}, {"ocr": "force"}, {"diarise": True}])
def test_invalid_audio_fixture_option_is_refused(corpus, tmp_path, options):
    copy = _with_manifest_change(corpus, tmp_path, "de-speech", options=options)
    with pytest.raises(CorpusError, match="de-speech.*invalid audio options"):
        load_corpus(copy)


def test_audio_fixture_options_override_the_job_defaults(corpus, tmp_path):
    copy = _with_manifest_change(corpus, tmp_path, "de-speech", options={"vad_filter": False})
    fixture = next(f for f in load_corpus(copy).fixtures if f.id == "de-speech")
    assert fixture.audio_options().model_dump() == {"translate": False, "word_timestamps": False,
                                                    "vad_filter": False, "diarize": False}


def test_diarization_fixtures_carry_their_reference_speakers(fixture_by_id):
    for fixture_id, voices in (("de-two-speakers", 2), ("de-case-conference", 4)):
        fixture = fixture_by_id[fixture_id]
        assert fixture.audio_options().diarize
        assert len({t.speaker for t in fixture.speakers}) == voices


@pytest.mark.parametrize(("fixture_id", "changes", "message"), [
    ("de-speech", {"checks": ["wer", "der"]}, "speaker checks need options.diarize"),
    ("de-two-speakers", {"speakers": []}, "speakers belong exactly"),
    ("de-two-speakers", {"options": {}}, "speakers belong exactly"),
    ("de-two-speakers", {"reference": "Etwas ganz anderes."}, "must make up the reference"),
])
def test_inconsistent_diarization_fixture_is_refused(corpus, tmp_path, fixture_id, changes, message):
    copy = _with_manifest_change(corpus, tmp_path, fixture_id, **changes)
    with pytest.raises(CorpusError, match=message):
        load_corpus(copy)


def test_fixture_options_override_defaults_and_keep_the_fixture_language(corpus, tmp_path):
    copy = _with_manifest_change(corpus, tmp_path, "scan-pdf", options={"ocr": "force"})
    by_id = {f.id: f for f in load_corpus(copy).fixtures}
    forced = by_id["scan-pdf"].document_options()
    assert forced.ocr == "force" and forced.languages == ["de"]
    default = by_id["bad-text-layer"].document_options()
    assert default.ocr is None and default.languages == ["de"]


def test_corpus_measures_the_non_german_document_languages(corpus):
    measured = {lang for f in corpus.fixtures if f.kind == "document" for lang in f.document_options().languages}
    assert measured >= {"de", "fr", "it", "es"}



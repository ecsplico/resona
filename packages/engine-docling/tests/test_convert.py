def test_rapidocr_rejects_languages_whose_recognizer_weights_differ(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setitem(convert_module._RAPIDOCR_FAMILY, "en", "ppocrv5-latin")
    with pytest.raises(UnsupportedDocumentOptions, match="share one recognizer"):
        convert_document(FIXTURES / "scan.pdf", options=DocumentOptions(ocr="force", ocr_engine="rapidocr"))


def test_job_result_round_trips_through_json() -> None:
    result = convert_document(FIXTURES / "table.pdf", options=DocumentOptions(ocr="off"))

    restored = JobResult.model_validate_json(result.model_dump_json())

    assert restored == result
    assert restored.provenance.input_sha256 is not None
    assert restored.provenance.runtime_version is not None
    assert restored.provenance.runtime_version.startswith("docling==2.129")

def test_table_pdf_keeps_all_cells_and_two_column_reading_order() -> None:
    result = convert_document(FIXTURES / "table.pdf", options=DocumentOptions(ocr="off"))

    assert _table_cells(result.markdown) >= set(TABLE_CELLS)
    assert sum(1 for line in result.markdown.splitlines() if line.startswith("|")) == 4  # header, separator, 2 body rows
    order = [
        "Linkspalte Absatz eins",
        "Linkspalte Absatz zwei",
        "Rechtsspalte Absatz eins",
        "Rechtsspalte Absatz zwei",
    ]
    positions = [result.raw_text.index(marker) for marker in order]
    assert positions == sorted(positions)


def test_page_range_returns_only_selected_page() -> None:
    result = convert_document(
        FIXTURES / "digital.pdf",
        options=DocumentOptions(ocr="off", page_start=2, page_end=2),
    )

    assert [page.number for page in result.pages] == [2]
    assert "Übergewicht und Müdigkeit" in result.markdown
    assert "Dieses Dokument ist" not in result.markdown


@pytest.mark.parametrize(
    "fields",
    [
        {"page_start": 3, "page_end": 2},
        {"page_start": 0},
        {"unknown_field": True},
        {"languages": ["fr"]},
        {"ocr": "sometimes"},
    ],
)
def test_invalid_document_options_are_rejected(fields: dict[str, object]) -> None:
    with pytest.raises(ValidationError):
        DocumentOptions(**fields)


def test_unsupported_media_type_is_rejected_before_conversion(tmp_path: Path) -> None:
    source = tmp_path / "notes.docx"
    source.write_bytes(b"not really a docx")

    with pytest.raises(UnsupportedMediaType):
        convert_document(source, options=DocumentOptions(ocr="off"))


def test_ocrmac_is_rejected_off_macos(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(convert_module, "_host_platform", lambda: "linux")

    with pytest.raises(UnsupportedDocumentOptions, match="macOS"):
        convert_document(FIXTURES / "digital.pdf", options=DocumentOptions(ocr="force", ocr_engine="ocrmac"))



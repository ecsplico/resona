TABLE_CELLS = [
    "Äpfel", "Größe 12", "Übung 4", "Straße A",
    "Löwe 7", "Brücke B", "Fuß 9", "Mühle 21",
    "Öl 5", "Kälte C", "Höhe 88", "Wärme 6",
]  # fmt: skip


def _table_cells(markdown: str) -> set[str]:
    cells: set[str] = set()
    for line in markdown.splitlines():
        if line.startswith("|") and not re.fullmatch(r"\|[\s\-|]+\|", line):
            cells.update(cell.strip() for cell in line.strip().strip("|").split("|"))
    return cells


def test_digital_pdf_without_ocr_keeps_exact_german_text_per_page() -> None:
    result = convert_document(FIXTURES / "digital.pdf", options=DocumentOptions(ocr="off"))

    assert "Dieses Dokument ist ein synthetisches Testdokument." in result.markdown
    assert "Die Straße führt nördlich über die Brücke." in result.markdown
    assert "Übergewicht und Müdigkeit wurden nicht beobachtet." in result.markdown
    assert "Die Wärme im Büro bleibt im Rahmen der Vorgaben." in result.raw_text
    assert [page.number for page in result.pages] == [1, 2]
    assert "Dieses Dokument" in result.pages[0].text
    assert "Übergewicht" in result.pages[1].text
    assert result.kind == "document"
    assert [(stage.stage, stage.engine) for stage in result.provenance.stages] == [
        ("layout", "docling-layout"),
        ("layout", "docling-tableformer"),
    ]


@DARWIN_ONLY
@pytest.mark.parametrize("ocr", ["auto", "force"])
def test_scanned_pdf_recovers_german_words_with_ocrmac(ocr: str) -> None:
    result = convert_document(
        FIXTURES / "scan.pdf",
        options=DocumentOptions(ocr=ocr, ocr_engine="ocrmac", languages=["de"]),
    )

    for word in ("Schwellenwert", "Brücke", "Übergewicht", "Vorgaben"):
        assert word in result.markdown, word
    ocr_stage = next(stage for stage in result.provenance.stages if stage.stage == "ocr")
    # Apple Vision chooses its device itself and does not report it: recorded as 'auto', never 'metal'.
    assert (ocr_stage.engine, ocr_stage.accelerator) == ("ocrmac", "auto")
    assert [page.number for page in result.pages] == [1, 2]



def _vera(points: float) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(str(VERA), round(points * SCAN_DPI / 72))


def _wrap(text: str, font: ImageFont.FreeTypeFont, width: int) -> list[str]:
    lines: list[str] = []
    line = ""
    for word in text.split():
        candidate = f"{line} {word}" if line else word
        if line and font.getlength(candidate) > width:
            lines.append(line)
            line = word
        else:
            line = candidate
    if line:
        lines.append(line)
    return lines


def _text_page(paragraphs: list[str], points: float, *, top_px: int = SCAN_MARGIN_PX
               ) -> tuple[Image.Image, list[tuple[int, int, str]]]:
    """White 150 dpi page with wrapped paragraphs; returns the image and (x, y, line) per line."""
    image = Image.new("L", SCAN_PX, color=255)
    draw = ImageDraw.Draw(image)
    font = _vera(points)
    leading = round(font.size * 1.45)
    width = SCAN_PX[0] - 2 * SCAN_MARGIN_PX
    placed = []
    y = top_px
    for paragraph in paragraphs:
        for line in _wrap(paragraph, font, width):
            draw.text((SCAN_MARGIN_PX, y), line, fill=0, font=font)
            placed.append((SCAN_MARGIN_PX, y, line))
            y += leading
        y += leading
    return image, placed


def _degrade(image: Image.Image, *, seed: int, angle: float = 0.0, blur: float = 0.0,
             noise: float = 0.0) -> Image.Image:
    if angle:
        image = image.rotate(angle, resample=Image.Resampling.BICUBIC, fillcolor=255)
    if blur:
        image = image.filter(ImageFilter.GaussianBlur(blur))
    if noise:
        rng = np.random.default_rng(seed)
        pixels = np.asarray(image, dtype=np.float32) + rng.normal(0.0, noise, (image.height, image.width))
        image = Image.fromarray(np.clip(pixels, 0, 255).astype(np.uint8), mode="L")
    return image


def _image_pdf(path: Path, image: Image.Image, *, quality: int, overlay=None) -> None:
    """One A4 page showing ``image``; ``overlay(pdf)`` may draw on top (e.g. a text layer)."""
    pdf = canvas.Canvas(str(path), pagesize=A4, invariant=1)
    buffer = io.BytesIO()
    image.save(buffer, format="JPEG", quality=quality)
    buffer.seek(0)
    pdf.drawImage(ImageReader(buffer), 0, 0, width=A4[0], height=A4[1])
    if overlay is not None:
        overlay(pdf)
    pdf.showPage()
    pdf.save()



"""Generate the synthetic, non-sensitive Resona evaluation corpus and its MANIFEST.json.

Run from the repository root on macOS (``say`` with the German voice Anna is required):

    uv run --no-project --with reportlab --with pillow --with numpy \
        python eval/corpus/make_corpus.py

Every fixture is generated here from invented text; nothing is recorded from a person
and no private document is involved. The references below are the exact source texts.
The manifest pins each file's SHA-256; ``resona_eval`` refuses a corpus whose files do
not match it, and the corpus hash recorded with evaluations and baselines is the
SHA-256 of MANIFEST.json itself.

Outputs (next to this script):
  de_speech.wav     German speech (umlauts, ß), macOS ``say -v Anna``, 16 kHz mono PCM.
  de_numbers.wav    German speech with dates, times and numbers, same voice/format.
  silence.wav       6 s of very low-level white noise (seed 7, about -60 dBFS); no speech.
  digital.pdf       2 pages German text with a text layer (Helvetica).
  scan.pdf          the same text rasterized to grayscale JPEG pages, no text layer.
  table_columns.pdf page 1: 3x4 grid of 12 distinct cells; page 2: two text columns.
"""

from __future__ import annotations

import hashlib
import io
import json
import subprocess
import wave
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    FrameBreak,
    NextPageTemplate,
    PageBreak,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)

HERE = Path(__file__).resolve().parent
ARIAL = Path("/System/Library/Fonts/Supplemental/Arial.ttf")
GENERATOR = "eval/corpus/make_corpus.py"
LICENSE = f"CC0-1.0, generated by {GENERATOR}"
VOICE = "Anna"
SAMPLE_RATE = 16000

SPEECH = (
    "Die Prüfung der neuen Brücke ist abgeschlossen. "
    "Größere Schäden wurden nicht gefunden. "
    "Die Straße bleibt über das Wochenende geöffnet. "
    "Für Rückfragen steht das Büro gern zur Verfügung."
)
NUMBERS = (
    "Der Termin ist am 12. Mai um 14 Uhr. "
    "Bitte bringen Sie 3 Kopien und 25 Euro mit. "
    "Die Zimmernummer lautet 108."
)

PAGE_TEXT: list[list[str]] = [
    [
        "Bericht über die Prüfung der Messwerte.",
        "Die Größen liegen deutlich über dem Schwellenwert.",
        "Der Weg führt südlich an der Mühle vorbei.",
    ],
    [
        "Müdigkeit und Übelkeit wurden nicht festgestellt.",
        "Die Wärme im Gebäude bleibt im zulässigen Bereich.",
    ],
]

TABLE_TITLE = "Tabelle mit zwölf Zellen"
TABLE_CELLS: list[list[str]] = [
    ["Äpfel", "Größe 12", "Übung 4", "Straße A"],
    ["Löwe 7", "Brücke B", "Fuß 9", "Mühle 21"],
    ["Öl 5", "Kälte C", "Höhe 88", "Wärme 6"],
]
COLUMNS_TITLE = "Zweispaltiger Text"
COLUMN_LEFT = [
    "Linkspalte Absatz eins: Die Versuchsreihe beginnt im linken Feld.",
    "Linkspalte Absatz zwei: Sie endet vor der rechten Spalte.",
]
COLUMN_RIGHT = [
    "Rechtsspalte Absatz eins: Dieser Text folgt erst nach links.",
    "Rechtsspalte Absatz zwei: Das ist der letzte Satz des Testdokuments.",
]


def say_wav(text: str, path: Path) -> None:
    subprocess.run(
        ["say", "-v", VOICE, f"--data-format=LEI16@{SAMPLE_RATE}", "--file-format=WAVE",
         "-o", str(path), text],
        check=True,
    )


def make_silence(path: Path, seconds: float = 6.0) -> None:
    rng = np.random.default_rng(7)
    samples = rng.normal(0.0, 0.001, int(seconds * SAMPLE_RATE))
    pcm = np.clip(samples * 32767, -32768, 32767).astype("<i2")
    with wave.open(str(path), "wb") as out:
        out.setnchannels(1)
        out.setsampwidth(2)
        out.setframerate(SAMPLE_RATE)
        out.writeframes(pcm.tobytes())


def make_digital(path: Path) -> None:
    pdf = canvas.Canvas(str(path), pagesize=A4, invariant=1)
    for lines in PAGE_TEXT:
        text = pdf.beginText(2.5 * cm, A4[1] - 3 * cm)
        text.setFont("Helvetica", 13)
        text.setLeading(22)
        for line in lines:
            text.textLine(line)
        pdf.drawText(text)
        pdf.showPage()
    pdf.save()


def _raster_page(lines: list[str]) -> Image.Image:
    dpi = 150
    width, height = int(8.27 * dpi), int(11.69 * dpi)
    image = Image.new("L", (width, height), color=255)
    draw = ImageDraw.Draw(image)
    font = ImageFont.truetype(str(ARIAL), 40)
    y = int(2.5 * dpi)
    for line in lines:
        draw.text((int(0.9 * dpi), y), line, fill=0, font=font)
        y += 90
    return image


def make_scan(path: Path) -> None:
    pdf = canvas.Canvas(str(path), pagesize=A4, invariant=1)
    for lines in PAGE_TEXT:
        buffer = io.BytesIO()
        _raster_page(lines).save(buffer, format="JPEG", quality=70)
        buffer.seek(0)
        pdf.drawImage(ImageReader(buffer), 0, 0, width=A4[0], height=A4[1])
        pdf.showPage()
    pdf.save()


def make_table_columns(path: Path) -> None:
    styles = getSampleStyleSheet()
    body = styles["BodyText"]
    body.fontName = "Helvetica"
    body.fontSize = 12
    grid = Table(TABLE_CELLS, colWidths=[4 * cm] * 4)
    grid.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.8, colors.black)]))

    doc = BaseDocTemplate(str(path), pagesize=A4, leftMargin=2.5 * cm, rightMargin=2.5 * cm,
                          invariant=1)
    frame_full = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="full")
    column_width = (doc.width - 1 * cm) / 2
    frame_left = Frame(doc.leftMargin, doc.bottomMargin, column_width, doc.height, id="left")
    frame_right = Frame(doc.leftMargin + column_width + 1 * cm, doc.bottomMargin, column_width,
                        doc.height, id="right")
    doc.addPageTemplates([
        PageTemplate(id="single", frames=[frame_full]),
        PageTemplate(id="columns", frames=[frame_left, frame_right]),
    ])
    story = [Paragraph(TABLE_TITLE, styles["Heading2"]), Spacer(1, 0.4 * cm), grid,
             NextPageTemplate("columns"), PageBreak(),
             Paragraph(COLUMNS_TITLE, styles["Heading2"]), Spacer(1, 0.3 * cm)]
    for paragraph in COLUMN_LEFT:
        story += [Paragraph(paragraph, body), Spacer(1, 0.3 * cm)]
    story.append(FrameBreak())
    for paragraph in COLUMN_RIGHT:
        story += [Paragraph(paragraph, body), Spacer(1, 0.3 * cm)]
    doc.build(story)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    say_wav(SPEECH, HERE / "de_speech.wav")
    say_wav(NUMBERS, HERE / "de_numbers.wav")
    make_silence(HERE / "silence.wav")
    make_digital(HERE / "digital.pdf")
    make_scan(HERE / "scan.pdf")
    make_table_columns(HERE / "table_columns.pdf")

    page_text = "\n".join(" ".join(lines) for lines in PAGE_TEXT)
    table_reference = "\n".join(
        [TABLE_TITLE, *(" ".join(row) for row in TABLE_CELLS), COLUMNS_TITLE, *COLUMN_LEFT, *COLUMN_RIGHT]
    )
    speech_source = f"synthetic German speech, macOS `say -v {VOICE}` (text invented for testing)"
    doc_source = "synthetic German document, reportlab (text invented for testing)"
    fixtures = [
        {"id": "de-speech", "kind": "audio", "file": "de_speech.wav", "language": "de",
         "source": speech_source, "reference": SPEECH, "checks": ["wer", "cer"]},
        {"id": "de-numbers", "kind": "audio", "file": "de_numbers.wav", "language": "de",
         "source": speech_source, "reference": NUMBERS, "checks": ["wer", "cer"]},
        {"id": "silence", "kind": "audio", "file": "silence.wav", "language": "de",
         "source": "synthetic low-level white noise (numpy, seed 7), no speech",
         "reference": "", "checks": ["silence"]},
        {"id": "digital-pdf", "kind": "document", "file": "digital.pdf", "language": "de",
         "source": doc_source + ", text layer", "reference": page_text, "checks": ["cer"]},
        {"id": "scan-pdf", "kind": "document", "file": "scan.pdf", "language": "de",
         "source": doc_source + ", rasterized JPEG pages without text layer (PIL, Arial)",
         "reference": page_text, "checks": ["cer"]},
        {"id": "table-columns-pdf", "kind": "document", "file": "table_columns.pdf", "language": "de",
         "source": doc_source + ", 3x4 table page and two-column page",
         "reference": table_reference, "checks": ["cer", "table_cells", "reading_order"],
         "table_cells": [cell for row in TABLE_CELLS for cell in row],
         "reading_order": [TABLE_TITLE, TABLE_CELLS[0][0], TABLE_CELLS[2][3], COLUMNS_TITLE,
                           COLUMN_LEFT[0], COLUMN_LEFT[1], COLUMN_RIGHT[0], COLUMN_RIGHT[1]]},
    ]
    for fixture in fixtures:
        fixture["sha256"] = _sha256(HERE / fixture["file"])
        fixture["license"] = LICENSE
    manifest = {"schema_version": 1, "generator": GENERATOR, "fixtures": fixtures}
    (HERE / "MANIFEST.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
                                        encoding="utf-8")
    for fixture in fixtures:
        print(fixture["id"], (HERE / fixture["file"]).stat().st_size, "bytes")


if __name__ == "__main__":
    main()
